export const aes128CtrCrypt = (key: Buffer, counter: Buffer, data: Buffer): Buffer => {
  if (key.length !== 16 || counter.length !== 16)
    throw new RangeError('AES key and counter must have 16 bytes');
  const ctr = Buffer.from(counter).reverse();
  const aes = createAesBlockCipher(Buffer.from(key).reverse());
  const output = Buffer.alloc(data.length);
  for (let p = 0; p < data.length; p += 16) {
    const mask = aes(ctr);
    for (let j = 0; j < 16 && p + j < data.length; j++) output[p + j] = data[p + j] ^ mask[15 - j];
    for (let j = 15; j >= 0; j--) {
      ctr[j] = (ctr[j] + 1) & 255;
      if (ctr[j]) break;
    }
  }
  return output;
};

export const modcryptKey = (header: ModcryptHeader): Buffer => {
  if (typeof header.gameCode !== 'string' || header.gameCode.length !== 4)
    throw new Error('Expected four-character game code');
  if (header.twlInternalFlags & 4 || (header.appflags?.[3] ?? 0) & 0x80) {
    const key = Buffer.alloc(16);
    key.write(header.gameTitle, 0, 12, 'ascii');
    key.write(header.gameCode, 12, 4, 'ascii');
    return key;
  }
  if (!header.hmac_arm9i || header.hmac_arm9i.length < 16)
    throw new Error('Missing ARM9i HMAC for modcrypt key');
  const x = Buffer.from(
    'Nintendo' + header.gameCode + [...header.gameCode].reverse().join(''),
    'ascii',
  );
  for (let i = 0; i < 16; i++) x[i] ^= header.hmac_arm9i[i];
  const mask = (1n << 128n) - 1n;
  let v = x.readBigUInt64LE(0) | (x.readBigUInt64LE(8) << 64n);
  v = (v + 0xfffefb4e295902582a680f5f1a4f3e79n) & mask;
  v = ((v << 42n) | (v >> 86n)) & mask;
  const out = Buffer.alloc(16);
  out.writeBigUInt64LE(v & ((1n << 64n) - 1n));
  out.writeBigUInt64LE(v >> 64n, 8);
  return out;
};

export const encryptSecureArea = (gameCode: string, input: Buffer): Buffer => {
  if (typeof gameCode !== 'string' || gameCode.length !== 4)
    throw new Error('Expected four-character game code');
  if (input.length < 0x800) throw new RangeError('Secure area must contain at least 0x800 bytes');
  const output = Buffer.from(input);
  let magic = new Uint32Array(0x412);
  let args: [number, number, number] = [0, 0, 0];
  function encrypt(a: number, b: number): [number, number] {
    for (let i = 0; i < 16; i++) {
      const c = (magic[i] ^ a) >>> 0;
      const sum = (magic[18 + (c >>> 24)] + magic[274 + ((c >>> 16) & 255)]) >>> 0;
      const f = (magic[786 + (c & 255)] + (magic[530 + ((c >>> 8) & 255)] ^ sum)) >>> 0;
      a = (b ^ f) >>> 0;
      b = c;
    }
    return [(b ^ magic[17]) >>> 0, (a ^ magic[16]) >>> 0];
  }
  function init2() {
    [args[2], args[1]] = encrypt(args[2], args[1]);
    [args[1], args[0]] = encrypt(args[1], args[0]);
    const key = Buffer.alloc(12);
    args.forEach((v, i) => key.writeUInt32LE(v, i * 4));
    for (let j = 0; j < 18; j++) magic[j] ^= key.readUInt32BE((j * 4) & 7);
    let a = 0,
      b = 0;
    for (let i = 0; i < 0x412; i += 2) {
      [a, b] = encrypt(a, b);
      magic[i] = a;
      magic[i + 1] = b;
    }
  }
  function init1() {
    magic = Uint32Array.from({ length: 0x412 }, (_, i) => KEY1.readUInt32LE(i * 4));
    const code = Buffer.from(gameCode, 'ascii').readUInt32LE();
    args = [code, code >>> 1, (code << 1) >>> 0];
    init2();
    init2();
  }
  init1();
  args[1] = (args[1] << 1) >>> 0;
  args[2] >>>= 1;
  init2();
  for (let p = 8; p < 0x800; p += 8) {
    const [b, a] = encrypt(output.readUInt32LE(p + 4), output.readUInt32LE(p));
    output.writeUInt32LE(a, p);
    output.writeUInt32LE(b, p + 4);
  }
  let [b, a] = encrypt(0x6a624f79, 0x72636e65);
  init1();
  [b, a] = encrypt(b, a);
  output.writeUInt32LE(a, 0);
  output.writeUInt32LE(b, 4);
  return output;
};
